/**
 * Encode a string for use inside a single-quoted Python literal in app.conf.
 * Doubles backslashes so they round-trip unchanged, and replaces ' with the
 * legacy {s-quote} placeholder that the backend converts back per use.
 */
function encode_python_string($val) {
  return str_replace(['\\', '\''], ['\\\\', '{s-quote}'], $val);
}
// -------------------------------------------------------------------------------------------
// Helper function to send notifications via the backend API endpoint
// -------------------------------------------------------------------------------------------
function displayInAppNoti($message, $level = 'error') {
    try {
        $apiBase = getSettingValue('BACKEND_API_URL') ?: 'http://localhost:20212';
        $apiToken = getSettingValue('API_TOKEN') ?: '';

        if (empty($apiToken)) {
            // If no token available, silently fail (don't break the application)
            return;
        }

        $url = rtrim($apiBase, '/') . '/messaging/in-app/write';
        $payload = json_encode([
            'message' => $message,
            'level' => $level
        ]);

        $ch = curl_init($url);
        curl_setopt($ch, CURLOPT_CUSTOMREQUEST, 'POST');
        curl_setopt($ch, CURLOPT_POSTFIELDS, $payload);
        curl_setopt($ch, CURLOPT_RETURNTRANSFER, true);
        curl_setopt($ch, CURLOPT_HTTPHEADER, [
            'Content-Type: application/json',
            'Authorization: Bearer ' . $apiToken,
            'Content-Length: ' . strlen($payload)
        ]);
        curl_setopt($ch, CURLOPT_TIMEOUT, 5);

        curl_exec($ch);
        curl_close($ch);
    } catch (Exception $e) {
        // Silently fail if notification sending fails
    }
}
